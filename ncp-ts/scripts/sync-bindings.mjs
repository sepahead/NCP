// Copy the ts-rs-generated reference JSON-projection shapes from
// ncp-core/bindings/*.ts into this package's src/generated/ so the package is
// self-contained for git / npm consumption. Shape parity reduces drift; it does
// not by itself qualify an installed peer or prove interoperability.
//
// Run after regenerating the bindings:
//   cargo test -p ncp-core --features ts   # rewrites ncp-core/bindings/*.ts
//   node ncp-ts/scripts/sync-bindings.mjs  # mirrors them here
//   tsc -p ncp-ts/tsconfig.json            # rebuilds ncp-ts/dist
// (or just `npm run regen` from the repo root, which chains all three).
import { mkdirSync, readdirSync, readFileSync, unlinkSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url)) // ncp-ts/scripts
const rustSrc = join(here, '..', '..', 'ncp-core', 'src') // ncp-core/src
const src = join(here, '..', '..', 'ncp-core', 'bindings') // ncp-core/bindings
const dst = join(here, '..', 'src', 'generated') // ncp-ts/src/generated
const tsRsHeader = '// This file was generated by [ts-rs]'

function rustSourceFiles(directory) {
  const files = []
  for (const entry of readdirSync(directory, { withFileTypes: true }).sort((a, b) =>
    a.name.localeCompare(b.name),
  )) {
    const path = join(directory, entry.name)
    if (entry.isDirectory()) files.push(...rustSourceFiles(path))
    else if (entry.isFile() && entry.name.endsWith('.rs')) files.push(path)
  }
  return files
}

function bracketDelta(line) {
  let delta = 0
  let quoted = false
  let escaped = false
  for (const character of line) {
    if (quoted) {
      if (escaped) escaped = false
      else if (character === '\\') escaped = true
      else if (character === '"') quoted = false
    } else if (character === '"') quoted = true
    else if (character === '[') delta += 1
    else if (character === ']') delta -= 1
  }
  return delta
}

function exportedTypeNames(path) {
  const names = []
  const pendingAttributes = []
  let attribute = []
  let attributeDepth = 0

  for (const line of readFileSync(path, 'utf8').split(/\r?\n/u)) {
    const trimmed = line.trim()
    if (attributeDepth > 0) {
      attribute.push(trimmed)
      attributeDepth += bracketDelta(trimmed)
      if (attributeDepth === 0) {
        pendingAttributes.push(attribute.join('\n'))
        attribute = []
      } else if (attributeDepth < 0) {
        throw new Error(`unbalanced Rust attribute in ${path}`)
      }
      continue
    }
    if (trimmed.startsWith('#[')) {
      attribute = [trimmed]
      attributeDepth = bracketDelta(trimmed)
      if (attributeDepth === 0) {
        pendingAttributes.push(attribute.join('\n'))
        attribute = []
      } else if (attributeDepth < 0) {
        throw new Error(`unbalanced Rust attribute in ${path}`)
      }
      continue
    }
    if (trimmed === '' || trimmed.startsWith('//')) continue

    const item = trimmed.match(/^pub\s+(?:struct|enum)\s+([A-Za-z_][A-Za-z0-9_]*)\b/u)
    if (item) {
      const attributes = pendingAttributes.join('\n')
      if (
        /\bfeature\s*=\s*"ts"/u.test(attributes) &&
        /\bts\s*\([\s\S]*?\bexport\b/u.test(attributes)
      ) {
        if (/\b(?:export_to|rename)\b/u.test(attributes)) {
          throw new Error(`unsupported ts-rs output-name attribute for ${item[1]} in ${path}`)
        }
        names.push(item[1])
      }
    }
    pendingAttributes.length = 0
  }
  if (attributeDepth !== 0) throw new Error(`unterminated Rust attribute in ${path}`)
  return names
}

function authoritativeTypes() {
  const names = rustSourceFiles(rustSrc).flatMap(exportedTypeNames).sort()
  if (names.length === 0) throw new Error('no exported ts-rs reference types found')
  const unique = new Set(names)
  if (unique.size !== names.length) throw new Error('duplicate exported ts-rs type name')
  return names
}

function typescriptFiles(directory) {
  const files = []
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    if (!entry.name.endsWith('.ts')) continue
    if (!entry.isFile()) {
      throw new Error(`refusing non-regular TypeScript binding path: ${join(directory, entry.name)}`)
    }
    files.push(entry.name)
  }
  return files.sort()
}

function obsoleteGeneratedTypes(directory, expectedFiles, allowBarrel) {
  const obsolete = []
  for (const file of typescriptFiles(directory)) {
    if (expectedFiles.has(file) || (allowBarrel && file === 'index.ts')) continue
    const path = join(directory, file)
    if (!readFileSync(path, 'utf8').startsWith(tsRsHeader)) {
      throw new Error(`refusing to remove non-ts-rs TypeScript file: ${path}`)
    }
    obsolete.push(path)
  }
  return obsolete
}

mkdirSync(dst, { recursive: true })
const types = authoritativeTypes()
const files = types.map((name) => `${name}.ts`)
const expectedFiles = new Set(files)
for (const file of files) {
  const path = join(src, file)
  let source
  try {
    source = readFileSync(path, 'utf8')
  } catch (error) {
    throw new Error(`missing ts-rs output for exported type ${file}`, { cause: error })
  }
  if (!source.startsWith(tsRsHeader)) {
    throw new Error(`expected ts-rs output header in ${path}`)
  }
}
const obsoleteFiles = [
  ...obsoleteGeneratedTypes(src, expectedFiles, true),
  ...obsoleteGeneratedTypes(dst, expectedFiles, true),
]
for (const path of obsoleteFiles) unlinkSync(path)

for (const f of files) {
  const source = readFileSync(join(src, f), 'utf8')
  // ts-rs 12 can leave spaces before newlines when a documented field forces a
  // multiline declaration. Normalize generated bytes so `git diff --check`
  // remains a reproducible gate rather than depending on generator trivia.
  const normalizedSource = `${source.replace(/[ \t]+$/gm, '').trimEnd()}\n`
  if (normalizedSource !== source) writeFileSync(join(src, f), normalizedSource)
  // ts-rs emits extensionless relative imports. They work through bundlers but
  // are invalid in the native Node ESM loader and under TypeScript NodeNext.
  // TypeScript resolves a `.js` source specifier back to the sibling `.ts` file
  // and preserves it in both emitted JavaScript and declaration files.
  const nodeEsmSource = normalizedSource.replace(
    /(\bfrom\s+['"])(\.\.?\/[^'"]+)(['"])/g,
    (_match, prefix, specifier, suffix) =>
      `${prefix}${specifier.endsWith('.js') ? specifier : `${specifier}.js`}${suffix}`,
  )
  writeFileSync(join(dst, f), nodeEsmSource)
}

// ts-rs writes one file per exported type but does not maintain either barrel.
// Rebuild both barrels from the actual files so a newly added reference type
// cannot exist on disk yet remain unreachable from either supported surface.
const header = [
  '// NCP reference JSON-projection types — GENERATED from ncp-core via ts-rs.',
  '// Shape parity reduces drift; it does not by itself prove interoperability.',
  '// Do not edit by hand; run `bun run regen` from the repository root.',
]
const sourceBarrel = [
  ...header,
  ...types.map((name) => `export type { ${name} } from './${name}';`),
  '',
].join('\n')
const packageBarrel = [
  ...header,
  ...types.map((name) => `export type { ${name} } from './${name}.js';`),
  '',
].join('\n')
writeFileSync(join(src, 'index.ts'), sourceBarrel)
writeFileSync(join(dst, 'index.ts'), packageBarrel)

console.log(`synced ${types.length} bindings: ncp-core/bindings -> ncp-ts/src/generated`)
