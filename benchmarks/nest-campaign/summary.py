#!/usr/bin/env python3
"""Write summary.md, the tables of the NEST campaign, from the analysis files.

Usage: summary.py. Reads results-2/analysis.json (protocol 2) and results-content/analysis.json
(the content protocol) next to this file and writes summary.md. Standard library only.
"""

from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ARMS = ("ncp-py-1.0.0", "ncp-py-1.0.1", "ncp-rs-1.0.1")
SPIKE_ARMS = ("ncp-py-1.0.1-spikes", "ncp-rs-1.0.1-spikes")


def cell(entry: dict | None, scale: float = 1.0, digits: int = 2) -> str:
    if not entry:
        return "–"
    return f"{entry['median'] * scale:.{digits}f} ({entry['min'] * scale:.{digits}f}–{entry['max'] * scale:.{digits}f})"


def main() -> None:
    timing = json.loads((HERE / "results-2" / "analysis.json").read_text())
    content = json.loads((HERE / "results-content" / "analysis.json").read_text())
    lines = [
        "# NEST campaign: tables",
        "",
        "Generated by `summary.py` from `results-2/analysis.json` (protocol 2) and `results-content/analysis.json`.",
        f"Protocol 2: {timing['runs']} of {timing['expected_runs']} runs, {len(timing['invalid_runs'])} invalid, "
        f"{len(timing['count_disagreements'])} disagreements of recorded spike counts between arms.",
        "",
        "Values are the median over three blocks, with the smallest and largest block value.",
        "",
    ]
    configurations = timing["configurations"]
    for part, title, arms in (
        ("D1", "Brunel network: NCP cost per exchange O, in ms", ARMS),
        ("D2", "Alpha and adaptive networks: NCP cost per exchange O, in ms", ARMS),
        ("D3", "Network size at 8 threads and Δ = 1 ms: NCP cost per exchange O, in ms", ARMS[1:]),
        ("D4", "Spikes returned at each step: NCP cost per exchange O, in ms", SPIKE_ARMS),
    ):
        lines += [f"## {part}. {title}", "", "| Network | Neurons | Threads | Δ (ms) | " + " | ".join(arms)
                  + " | MUSIC, s per run |", "| --- | ---: | ---: | ---: |" + " ---: |" * (len(arms) + 1)]
        for key, entry in sorted(configurations.items(), key=lambda item: (item[1]["network"], item[1]["n"],
                                                                         item[1]["threads"], item[1]["delta_ms"])):
            if entry["part"] != part:
                continue
            ncp = entry.get("ncp_ms_per_exchange", {})
            cells = [cell(ncp.get(arm)) for arm in arms]
            lines.append(f"| {entry['network']} | {entry['n']} | {entry['threads']} | {entry['delta_ms']:g} | "
                         + " | ".join(cells) + f" | {cell(entry.get('music_s_per_run'), digits=3)} |")
        lines.append("")
    lines += ["## Hypotheses of protocol 2", "", "| # | Criterion | Holds |", "| --- | --- | --- |"]
    for name, entry in timing["hypotheses"].items():
        lines.append(f"| {name} | {entry['criterion']} | {'yes' if entry['holds'] else 'no'} |")
    lines += ["", "## Content: exact spike delivery", "",
              f"{content['trials']} trials, {len(content['failed'])} failed.", "",
              "| NEST threads | Trials | NCP exact | MUSIC exact | MUSIC channels with the exact train (of 1000) |",
              "| ---: | ---: | ---: | ---: | --- |"]
    for threads, entry in sorted(content["by_threads"].items(), key=lambda item: int(item[0])):
        low, high = entry["music_channels_exact_min"], entry["music_channels_exact_max"]
        lines.append(f"| {threads} | {entry['trials']} | {entry['ncp_exact']} | {entry['music_exact']} | "
                     + (f"{low}" if low == high else f"{low} to {high}") + " |")
    lines += ["", "| # | Criterion | Holds |", "| --- | --- | --- |"]
    for name, entry in content["hypotheses"].items():
        lines.append(f"| {name} | {entry['criterion']} | {'yes' if entry['holds'] else 'no'} |")
    (HERE / "summary.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
